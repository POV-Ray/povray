//##############################################################################
///
/// @defgroup PovBaseBuiltinFiles Built-in Standard Include Files
/// @ingroup PovBase
///
/// The files of `distribution/include` (the standard include files, colour maps,
/// images and fonts) are compiled into the program, deflated, so that a scene can
/// use them when they are not installed. The table is generated by
/// `tools/meta-make/builtinfiles/metagen-builtinfiles.py` into
/// `source/base/builtinfiles_data.cpp`.
///
/// A built-in file is known by its _pseudo-path_, `<builtin>/` followed by its
/// name, with a forward slash on every platform; that is the name messages show,
/// and the name a scene may use to ask for the built-in copy explicitly. No
/// Windows file name can contain `<`, and the front end never looks for a name
/// with this prefix on disk.
///
/// Names are compared exactly, including their case, on every platform, so a
/// scene behaves the same with the built-in files as with installed ones on a
/// file system that distinguishes case.
///
/// @{

/// One file of the built-in table.
struct BuiltinFileEntry
{
    const char*          name;          ///< Bare file name, e.g. `colors.inc`.
    size_t               size;          ///< Size of the file.
    size_t               deflatedSize;  ///< Size of the zlib stream at @ref data.
    const unsigned char* data;          ///< The file's contents, as a zlib stream.
};

/// The built-in files, sorted by name (byte values). Generated.
extern const BuiltinFileEntry kBuiltinFiles[];

/// Number of entries in @ref kBuiltinFiles. Generated.
extern const size_t kBuiltinFileCount;

/// Prefix of a pseudo-path, `<builtin>/`.
extern const char kBuiltinFilePrefix[];

/// Find a built-in file by its bare name, e.g. `colors.inc`.
///
/// The comparison is exact, including case. A name with any directory part
/// (a `/`, `\` or `:`) never matches; nor does a pseudo-path (see
/// @ref FindBuiltinFileByPath()).
///
/// @return     The table entry, or `nullptr` if there is no such file.
///
const BuiltinFileEntry* FindBuiltinFile(const UCS2String& name);

/// Tell whether a name is a pseudo-path, i.e. starts with `<builtin>/`.
///
/// This says nothing about whether such a built-in file exists.
///
bool IsBuiltinFilePath(const UCS2String& name);

/// Find a built-in file by its pseudo-path, e.g. `<builtin>/colors.inc`.
///
/// What follows the prefix must be the exact name of a built-in file, so
/// `<builtin>/sub/x.inc` and `<builtin>/../x` do not match.
///
/// @return     The table entry, or `nullptr` if @p path is not a pseudo-path or
///             names no built-in file.
///
const BuiltinFileEntry* FindBuiltinFileByPath(const UCS2String& path);

/// Pseudo-path of a built-in file, e.g. `<builtin>/colors.inc`.
UCS2String BuiltinFilePath(const BuiltinFileEntry& entry);

/// Tell whether a built-in file is one of the standard include (`.inc`) files.
///
/// Only these decide whether a render uses the built-in files or those on disk:
/// a library path holding one of them means the files on disk are used.
///
bool IsBuiltinIncludeFile(const BuiltinFileEntry& entry);

/// Open a built-in file for reading.
///
/// The stream is named by the file's pseudo-path. The inflated contents are kept
/// (see @ref ReleaseBuiltinFileCache()), so that a file opened many times, such
/// as an include file whose macros are called from elsewhere, is inflated once.
/// No I/O restrictions apply: the file is part of the program.
///
/// @return     A new stream, owned by the caller.
/// @throw      pov_base::Exception if the stored data is damaged.
///
IMemStream* OpenBuiltinFile(const BuiltinFileEntry& entry);

/// Open a built-in file named by its pseudo-path.
///
/// @return     A new stream, owned by the caller, or `nullptr` if @p path names no
///             built-in file.
///
IMemStream* OpenBuiltinFile(const UCS2String& path);

/// Drop the inflated copies kept by @ref OpenBuiltinFile().
///
/// Streams that are still open keep their data. The front end calls this when a
/// new render job starts.
///
void ReleaseBuiltinFileCache();

/// @}
